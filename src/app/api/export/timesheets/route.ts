import { NextResponse, type NextRequest } from "next/server";
import { getAppContext } from "@/lib/auth";
import { getRangeSummary } from "@/lib/data/sessions";
import { fileResponse, renderPdf, toCsv } from "@/lib/export";
import { addDaysToKey, breakMinutes, formatLocal, sessionWorkedMinutes, toHours } from "@/lib/time/calc";

const KEY = /^\d{4}-\d{2}-\d{2}$/;

export async function GET(request: NextRequest) {
  const ctx = await getAppContext();
  if (!ctx) return NextResponse.json({ error: "Not signed in" }, { status: 401 });

  const sp = request.nextUrl.searchParams;
  const from = sp.get("from") ?? "";
  const to = sp.get("to") ?? "";
  const format = sp.get("format") === "pdf" ? "pdf" : "csv";
  if (!KEY.test(from) || !KEY.test(to) || to <= from || to > addDaysToKey(from, 400)) {
    return NextResponse.json({ error: "Invalid date range" }, { status: 400 });
  }
  if (format === "pdf" && !ctx.entitlements.has("pdf_reports")) {
    return NextResponse.json({ error: "PDF reports are part of Apprentice OS Pro" }, { status: 402 });
  }

  const [{ sessions, totals }, { data: employers }, { data: sites }] = await Promise.all([
    getRangeSummary(ctx, from, to),
    ctx.supabase.from("employers").select("id, name"),
    ctx.supabase.from("job_sites").select("id, name"),
  ]);
  const name = (list: { id: string; name: string }[] | null, id: string | null) => (id ? (list?.find((x) => x.id === id)?.name ?? "") : "");
  const tz = ctx.profile.timezone;

  const inRange = sessions.filter((s) => {
    const k = formatLocal(s.started_at, s.timezone || tz, "yyyy-MM-dd");
    return k >= from && k < to;
  });

  const rows = inRange.map((s) => {
    const z = s.timezone || tz;
    const worked = sessionWorkedMinutes(s, s.breaks);
    return {
      date: formatLocal(s.started_at, z, "yyyy-MM-dd"),
      day: formatLocal(s.started_at, z, "EEE"),
      start: formatLocal(s.started_at, z, "HH:mm"),
      finish: s.ended_at ? formatLocal(s.ended_at, z, "HH:mm") : "in progress",
      breakMin: Math.round(breakMinutes(s, s.breaks, Date.now(), "unpaid")),
      hours: toHours(worked),
      employer: name(employers, s.employer_id),
      site: name(sites, s.job_site_id),
      address: s.start_address ?? "",
      locationSource: s.start_location_source,
      status: s.approval_status,
      notes: s.notes ?? "",
    };
  });

  const stamp = `${from}_to_${addDaysToKey(to, -1)}`;
  if (format === "csv") {
    const csv = toCsv(
      ["Date", "Day", "Start", "Finish", "Unpaid break (min)", "Hours worked", "Employer", "Job site", "Address (approx.)", "Location source", "Status", "Notes"],
      rows.map((r) => [r.date, r.day, r.start, r.finish, r.breakMin, r.hours.toFixed(2), r.employer, r.site, r.address, r.locationSource, r.status, r.notes]),
    );
    return fileResponse(csv, `timesheet_${stamp}.csv`, "text/csv; charset=utf-8");
  }

  const pdf = renderPdf({
    title: "Timesheet",
    subtitle: `${formatLocal(`${from}T12:00:00Z`, "UTC", "d MMMM yyyy")} – ${formatLocal(`${addDaysToKey(to, -1)}T12:00:00Z`, "UTC", "d MMMM yyyy")}`,
    meta: [
      ["Apprentice", ctx.profile.full_name ?? ""],
      ["Timezone", tz],
      ["Ordinary hours", `${ctx.rules.daily_ordinary_hours}h/day, ${ctx.rules.weekly_ordinary_hours}h/week (user-configured)`],
    ],
    headers: ["Date", "Start", "Finish", "Break", "Hours", "Employer", "Job site", "Status"],
    rows: rows.map((r) => [`${r.day} ${r.date}`, r.start, r.finish, `${r.breakMin}m`, r.hours.toFixed(2), r.employer, r.site || r.address, r.status]),
    columnStyles: { 4: { halign: "right" } },
    summary: [
      ["Total hours", toHours(totals.totalMinutes).toFixed(2)],
      ["Ordinary", toHours(totals.ordinaryMinutes).toFixed(2)],
      ["Overtime", toHours(totals.overtimeMinutes).toFixed(2)],
      ["Weekend", toHours(totals.weekendMinutes).toFixed(2)],
      ["Public holiday", toHours(totals.holidayMinutes).toFixed(2)],
    ],
    footnote:
      "Generated by Apprentice OS from the apprentice's own records. Hour categories follow the rules configured by the apprentice and are not an award interpretation. Addresses are approximate.",
  });
  return fileResponse(pdf, `timesheet_${stamp}.pdf`, "application/pdf");
}
